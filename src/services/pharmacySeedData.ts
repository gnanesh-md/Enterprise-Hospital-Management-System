/**
 * Checks if pharmacy database has valid records.
 * If empty, automatically seeds realistic hospital formulary data.
 */
export function ensurePharmacyDataSeeded(): void {
  if (typeof window === "undefined") return

  const medicinesKey = "hospai_pharm_medicines_v4"
  const batchesKey = "hospai_pharm_batches_v4"

  const storedMeds = window.localStorage.getItem(medicinesKey)
  const storedBatches = window.localStorage.getItem(batchesKey)

  const hasMeds = storedMeds && storedMeds !== "[]" && JSON.parse(storedMeds).length > 0
  const hasBatches = storedBatches && storedBatches !== "[]" && JSON.parse(storedBatches).length > 0

  if (!hasMeds || !hasBatches) {
    seedPharmacyHospitalData(true)
  }
}
