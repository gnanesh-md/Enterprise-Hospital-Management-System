// ── Seeding Helper Functions ────────────────────────────────────────────────

export function seedPharmacyHospitalData(force: boolean = false) {
  if (typeof window === "undefined") return

  const medicinesKey = "hospai_pharm_medicines_v4"
  const batchesKey = "hospai_pharm_batches_v4"
  const suppliersKey = "hospai_pharm_suppliers_v4"
  const categoriesKey = "hospai_pharm_categories_v4"
  const posKey = "hospai_pharm_pos_v4"
  const grnsKey = "hospai_pharm_grns_v4"
  const rxKey = "hospai_pharm_rx_v4"
  const billsKey = "hospai_pharm_bills_v4"
  const returnsKey = "hospai_pharm_returns_v4"
  const auditLogsKey = "hospai_pharm_audit_logs_v4"
  const notifsKey = "hospai_pharm_notifications_v4"

  const existingMeds = window.localStorage.getItem(medicinesKey)
  const isMedsEmpty = !existingMeds || existingMeds === "[]"

  if (force || isMedsEmpty) {
    window.localStorage.setItem(categoriesKey, JSON.stringify(SEED_CATEGORIES))
    window.localStorage.setItem(suppliersKey, JSON.stringify(SEED_SUPPLIERS))
    window.localStorage.setItem(medicinesKey, JSON.stringify(SEED_MEDICINES))
    window.localStorage.setItem(batchesKey, JSON.stringify(SEED_BATCHES))
    window.localStorage.setItem(posKey, JSON.stringify(SEED_PURCHASE_ORDERS))
    window.localStorage.setItem(grnsKey, JSON.stringify(SEED_GRNS))
    window.localStorage.setItem(returnsKey, JSON.stringify(SEED_RETURNS))
    window.localStorage.setItem(auditLogsKey, JSON.stringify(SEED_AUDIT_LOGS))
    window.localStorage.setItem(notifsKey, JSON.stringify(SEED_NOTIFICATIONS))

    // For prescriptions, merge with any existing ones
    const existingRxStr = window.localStorage.getItem(rxKey)
    let rxList: AppPrescription[] = existingRxStr ? JSON.parse(existingRxStr) : []
    const existingRxIds = new Set(rxList.map((r) => r.id))
    const toAddRx = SEED_PRESCRIPTIONS.filter((r) => !existingRxIds.has(r.id))
    rxList = [...toAddRx, ...rxList]
    window.localStorage.setItem(rxKey, JSON.stringify(rxList))

    // For bills, merge or set
    const existingBillsStr = window.localStorage.getItem(billsKey)
    let billsList: AppPharmacyBill[] = existingBillsStr ? JSON.parse(existingBillsStr) : []
    const existingBillIds = new Set(billsList.map((b) => b.id || b.billNumber))
    const toAddBills = SEED_BILLS.filter((b) => !existingBillIds.has(b.id) && !existingBillIds.has(b.billNumber))
    billsList = [...toAddBills, ...billsList]
    window.localStorage.setItem(billsKey, JSON.stringify(billsList))

    window.localStorage.setItem("hospai_pharm_fresh_clean_slate_v2026_ready", "true")

    window.dispatchEvent(new Event("storage"))
    window.dispatchEvent(new CustomEvent("hospai_pharmacy_updated"))
  }
}

